# ── Async API tests (pytest-asyncio) ────────────────────────────────────────

@allure.suite("API Regression Suite")
@allure.feature("Posts API")
@allure.story("Async GET post returns correct data")
@allure.severity(allure.severity_level.NORMAL)
async def test_async_get_post():
    """
    Async test using httpx — same pattern as calling an async LLM agent endpoint.
    Interview talking point: 'I use async tests when the system under test
    is an async FastAPI endpoint or an async LangGraph agent.'
    """
    async with httpx.AsyncClient() as client:
        with allure.step("Async GET /posts/1"):
            response = await client.get(f"{BASE_URL}/posts/1")

    with allure.step("Assert status 200 and body"):
        assert response.status_code == 200
        data = response.json()
        allure.attach(str(data), name="async_response",
                      attachment_type=allure.attachment_type.JSON)
        assert data["id"] == 1


@allure.suite("API Regression Suite")
@allure.feature("Posts API")
@allure.story("Async parallel API calls complete successfully")
@allure.severity(allure.severity_level.NORMAL)
async def test_async_parallel_calls():
    """
    Simulates async parallel calls — useful for load testing agent endpoints.
    """
    import asyncio

    async with httpx.AsyncClient() as client:
        with allure.step("Fire 3 parallel requests"):
            responses = await asyncio.gather(
                client.get(f"{BASE_URL}/posts/1"),
                client.get(f"{BASE_URL}/posts/2"),
                client.get(f"{BASE_URL}/posts/3"),
            )

    with allure.step("Assert all returned 200"):
        for resp in responses:
            assert resp.status_code == 200
