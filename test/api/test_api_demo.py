import allure
import pytest
import requests
import httpx


BASE_URL = "https://jsonplaceholder.typicode.com"


# ── Synchronous API tests ────────────────────────────────────────────────────

@allure.suite("API Smoke Suite")
@allure.feature("Posts API")
@allure.story("GET all posts returns 200")
@allure.severity(allure.severity_level.CRITICAL)
def test_get_posts_returns_200():
    with allure.step("Send GET /posts"):
        response = requests.get(f"{BASE_URL}/posts")

    with allure.step("Assert status 200"):
        allure.attach(str(response.status_code), name="status_code",
                      attachment_type=allure.attachment_type.TEXT)
        assert response.status_code == 200

    with allure.step("Assert response is a list"):
        data = response.json()
        assert isinstance(data, list)
        assert len(data) > 0


